"""Bake the GPL builtin model plus independently authored lut4 adjustments."""
from pathlib import Path
import tempfile,subprocess,sys,json,hashlib
from lutjpeg_recipe import validate,apply_table
root=Path(__file__).resolve().parents[1];m=root/'firmware/modules/lutjpeg';u=m/'upstream'
data=root/'firmware/data/lutjpeg'
spec_bytes=(data/'RECIPES.json').read_bytes();spec=json.loads(spec_bytes);validate(spec)
digest=hashlib.sha256(spec_bytes).hexdigest()
header=('/* Generated by tools/bake_lutjpeg_tables.py; recipe identity, not a security signature. */\n'
        f'#define LUTJPEG_RECIPE_TAG 0x{digest[:8]}u\n').encode()
version=m/'recipe-version.h'
if '--check' in sys.argv:assert version.read_bytes()==header,'Rebake recipe-version.h'
else:version.write_bytes(header)
hashes={}
with tempfile.TemporaryDirectory(prefix='lut-bake-') as tmp:
 p=Path(tmp)
 subprocess.run(['gcc','-O2','-DFOS_DEV_TEST','-DCONFIG_600D=1','-I'+str(u),str(root/'tests/lutjpeg/host.c'),str(m/'catalog.c')]+[str(u/n) for n in ['fos_dev.c','fos_jpeg.c','fos_print.c','fos_looks.c']]+['-lm','-o',str(p/'bake')],check=True)
 subprocess.run([str(p/'bake'),'-T',str(p)],check=True)
 for recipe in spec['looks']:
  name=f"LOOK{recipe['index']:02d}.LUT";dst=data/name
  baked=apply_table((p/name).read_bytes(),recipe,spec['sector_centres_degrees'])
  hashes[name]=hashlib.sha256(baked).hexdigest()
  if '--check' in sys.argv:assert dst.read_bytes()==baked,name
  else:dst.write_bytes(baked)
 metadata={'upstream_commit':'3a5b0d8506d6279b1b223f78612dfa6db47405e8',
           'origin':'GPL M-Film builtin model plus independent lut4 matrix/curve/HSV-sector/split-colour adjustments; not measured film scans or Olympus tables',
           'recipe_sha256':digest,'recipe_domain':spec['domain'],
           'indices':{f"LOOK{r['index']:02d}.LUT":r['key'] for r in spec['looks']},'sha256':hashes}
 encoded=(json.dumps(metadata,indent=2)+'\n').encode()
 if '--check' in sys.argv:assert (data/'TABLES.json').read_bytes()==encoded,'TABLES.json'
 else:(data/'TABLES.json').write_bytes(encoded)
 print('PASS three lut4 LUTs, recipe identity and manifest reproduce exactly')
